#!/usr/bin/env bash
# Register `dsh` as a global command on Linux (run once).
#
# Writes a wrapper to ~/.local/bin/dsh (or $DSH_BIN_DIR) that starts the built
# CLI of this checkout without changing the working directory, so the terminal
# directory stays the workspace, as dsh.cmd does on Windows.
#
# The CLI selects the profile (apps/cli/src/args.ts): `dsh` opens the terminal
# app, and `dsh --web` / `dsh -web` / `dsh web` the Web profile.
#
# Usage:
#   bash scripts/install-dsh-linux.sh              install the wrapper
#   bash scripts/install-dsh-linux.sh --build      run pnpm install and build:lib first
#   bash scripts/install-dsh-linux.sh --uninstall  remove the wrapper and the PATH line
set -euo pipefail

repo=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
bin_dir=${DSH_BIN_DIR:-"$HOME/.local/bin"}
target="$bin_dir/dsh"
cli="$repo/apps/cli/lib/bin.js"
marker='# dsh: PATH (scripts/install-dsh-linux.sh)'

build=0
uninstall=0
for arg in "$@"; do
  case "$arg" in
    --build) build=1 ;;
    --uninstall) uninstall=1 ;;
    -h|--help) sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "install-dsh-linux: unknown argument: $arg" >&2; exit 2 ;;
  esac
done

rc_files() {
  local f
  for f in "$HOME/.bashrc" "$HOME/.zshrc" "$HOME/.profile"; do
    [[ -f "$f" ]] && printf '%s\n' "$f"
  done
}

if (( uninstall )); then
  rm -f -- "$target"
  while IFS= read -r rc; do
    # Remove the marker and the export line after it.
    sed -i "\|^$marker\$|,+1d" "$rc"
  done < <(rc_files)
  echo "dsh removed ($target)."
  exit 0
fi

# --- Node ------------------------------------------------------------------
# package.json engines: node >=24.9.0
if ! command -v node >/dev/null 2>&1; then
  echo 'install-dsh-linux: node not found on PATH (requires >=24.9.0).' >&2
  exit 1
fi
if ! node -e '
  const [maj, min] = process.versions.node.split(".").map(Number);
  process.exit(maj > 24 || (maj === 24 && min >= 9) ? 0 : 1);
'; then
  echo "install-dsh-linux: node $(node -v) is not supported (requires >=24.9.0)." >&2
  exit 1
fi

# --- Build (optional) ------------------------------------------------------
if (( build )); then
  if ! command -v pnpm >/dev/null 2>&1; then
    echo 'install-dsh-linux: pnpm not found (run corepack enable, or npm i -g pnpm).' >&2
    exit 1
  fi
  (cd -- "$repo" && pnpm install && pnpm run build:lib)
fi

# --- Wrapper ---------------------------------------------------------------
mkdir -p -- "$bin_dir"
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by scripts/install-dsh-linux.sh: the working directory stays the dsh workspace.'
  printf 'cli=%q\n' "$cli"
  cat <<'EOF'
if [[ ! -f "$cli" ]]; then
  echo "dsh: the CLI is not built ($cli). Run 'pnpm build:lib' in the repository." >&2
  exit 1
fi
exec node "$cli" "$@"
EOF
} > "$target"
chmod +x -- "$target"
echo "dsh installed: $target -> $cli"

# --- PATH ------------------------------------------------------------------
case ":$PATH:" in
  *":$bin_dir:"*) on_path=1 ;;
  *) on_path=0 ;;
esac
if (( ! on_path )); then
  # The rc file of the login shell; .profile otherwise.
  case "${SHELL##*/}" in
    zsh) rc="$HOME/.zshrc" ;;
    bash) rc="$HOME/.bashrc" ;;
    *) rc="$HOME/.profile" ;;
  esac
  if ! grep -qxF "$marker" "$rc" 2>/dev/null; then
    printf '\n%s\nexport PATH=%q:"$PATH"\n' "$marker" "$bin_dir" >> "$rc"
    echo "Added $bin_dir to PATH in $rc."
  fi
  echo "Open a new terminal (or run: source $rc) to use dsh."
fi

if [[ ! -f "$cli" ]]; then
  echo "Note: the CLI is not built yet. Run 'pnpm install && pnpm build:lib' in $repo" >&2
  echo "      or run this script again with --build." >&2
fi
